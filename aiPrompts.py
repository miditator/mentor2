def generate_word_intensity_prompt(word, target_lang, difficulty, meanings=None, markers=None):
    if meanings is None: meanings = []
    if markers is None: markers = []

    lang_name = "английском (English)" if target_lang == "en" else "немецком (Deutsch)"
    diff = str(difficulty).strip().upper().replace("А", "A")
    level_rules = DIFFICULTY_RULES.get(diff, DIFFICULTY_RULES["A1"])

    meanings_instruction = ""
    if meanings:
        meanings_list_str = "\n".join([f"Значение {i + 1}: {m}" for i, m in enumerate(meanings)])
        meanings_instruction = f"""
    🎯 УСЛОВИЕ ДЛЯ РАЗНЫХ ЗНАЧЕНИЙ:
    Слово "{word}" имеет варианты: {meanings_list_str}. Распредели их по фразам (1 предложение — 1 значение).
        """

    # 🔥 Блок интеграции наших уникальных маркеров
    markers_instruction = ""
    if markers:
        markers_str = ", ".join(markers)
        markers_instruction = f"""
    🎯 ОБЯЗАТЕЛЬНОЕ ТРЕБОВАНИЕ К МАРКЕРАМ:
    При составлении 5 предложений органично вплети в них следующие грамматические маркеры/лова-указатели (по одному на предложение, где это уместно): [{markers_str}]. Не повторяй один маркер дважды!
        """

    return f"""
    Ты — профессиональный ИИ-ментор. Твоя задача — сгенерировать ровно 5 РАЗНЫХ предложений, в КАЖДОМ из которых ОБЯЗАТЕЛЬНО используется слово "{word}".
    {meanings_instruction}
    {markers_instruction}

    🚨 ВАЖНОЕ ПРАВИЛО ВАЛИДАЦИИ: 
    Сначала проверь, существует ли слово "{word}" в {lang_name} языке. Если это бред или опечатка, верни строго: {{"error": "invalid_word"}}

    📈 ТРЕБОВАНИЯ К СЛОЖНОСТИ (СТРОГО {diff}):
    ВСЕ 5 предложений должны соответствовать уровню {diff}:
    {level_rules}

    Для КАЖДОГО предложения в поле "rule" сформулируй конкретное грамматическое задание на русском языке, начиная с маркера уровня (например: "[{diff}] Переведи в Past Simple").

    Ответ выдай СТРОГО в формате JSON-массива из 5 объектов без markdown-разметки (без ```json):
    [
      {{"phrase": "Sentence 1", "translation": "Перевод 1", "rule": "[{diff}] Задание 1"}},
      ...
    ]
    """


