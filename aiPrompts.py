def generate_lego_task_prompt(lang_name, target_word, rule_name, mandatory_marker, background_words, difficulty, theme,
                              target_meaning=None):
    diff = str(difficulty).strip().upper().replace("А", "A")
    level_rules = DIFFICULTY_RULES.get(diff, DIFFICULTY_RULES["A1"])
    bg_str = ", ".join(background_words) if background_words else "не используй"

    # 🔥 ДЕЛАЕМ МАРКЕР АБСТРАКТНЫМ ОРИЕНТИРОМ, А НЕ ЖЕСТКИМ ТЕКСТОМ
    marker_str = f'\n4. Грамматический ориентир: "{mandatory_marker}" (Воспринимай это как подсказку для построения нужной грамматической конструкции. Тебе НЕ обязательно вставлять это дословно, главное — передать суть и задать правильное время).' if mandatory_marker else ""

    # 👈 ЖЕСТКОЕ ЗНАЧЕНИЕ СЛОВА
    meaning_str = f'\n5. 🛑 ЖЕСТКОЕ ЗНАЧЕНИЕ СЛОВА: Используй "{target_word}" СТРОГО в значении "{target_meaning}".' if target_meaning else ""

    return f"""Ты — методист по языкам и носитель {lang_name} языка. Создай одно предложение для перевода.

{level_rules}

ДАННЫЕ ДЛЯ ЗАДАНИЯ:
1. Инструкция по грамматике: {rule_name}
2. Целевое слово: "{target_word}".
3. Обязательная тема контекста: "{theme}".
4. Фоновые слова-кандидаты: [{bg_str}].{marker_str}{meaning_str}

АЛГОРИТМ:
1. Оставь только те фоновые слова, которые логично вписываются в тему "{theme}". Остальные выбрось.
2. Составь на {lang_name} языке одно предложение, строго выполнив "Инструкцию по грамматике". Опирайся на грамматический ориентир, включи целевое слово и подходящий фон.
3. Сделай точный, красивый литературный перевод на русский язык без калек.
4. Выведи результат СТРОГО в формате JSON без markdown-разметки:
{{
  "foreign_phrase": "предложение на {lang_name}",
  "russian_phrase": "русский перевод"
}}"""



